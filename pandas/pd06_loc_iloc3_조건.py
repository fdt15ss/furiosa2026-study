import pandas as pd
print(pd.__version__)   # 3.0.6

data = [
    ['삼성', 1000, 2000],
    ['현대', 1100, 3000],
    ['LG', 2000, 500],
    ['아모레', 3500, 6000],
    ['네이버', 100, 1500],
]

index = ['031', '059', '033', '045', '023']
columns = ['종목명', '시가', '종가']

df = pd.DataFrame(data=data, index=index, columns=columns)
print(df)
#      종목명    시가    종가
# 031   삼성  1000  2000
# 059   현대  1100  3000
# 033   LG  2000   500
# 045  아모레  3500  6000
# 023  네이버   100  1500

print("=================================")
print("시가가 1100원 이상인 행을 모두 출력!!")

# 맹그러봐

cond1 = df['시가']>= 1100
print(cond1)
print(df[cond1])
print(df[df['시가']>= 1100])
print("==========================")
print(df.loc[df['시가']>= 1100])
# print(df.iloc[df['시가']>=1100]) # 에러

########### 위에서 종가만 뽑고 싶어 #############
print("=============================")
print(df[df['시가']>=1100]['종가'])
print(df.loc[df['시가']>= 1100]['종가'])
print(df.loc[df['시가']>= 1100].loc[:, '종가'])